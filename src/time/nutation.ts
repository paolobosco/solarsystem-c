const N = TERMINI.length / 8;

/** Δψ (rad) all'istante JD TT, riferita all'eclittica e all'equinozio della data. */
export function nutazioneLongitudine(jdTT: number): number {
  const t = (jdTT - 2451545) / 36525;
  const el = ((485868.249036 + 1717915923.2178 * t) % TURNAS) * DAS2R;
  const elp = ((1287104.79305 + 129596581.0481 * t) % TURNAS) * DAS2R;
  const f = ((335779.526232 + 1739527262.8478 * t) % TURNAS) * DAS2R;
  const d = ((1072260.70369 + 1602961601.209 * t) % TURNAS) * DAS2R;
  const om = ((450160.398036 + -6962890.5431 * t) % TURNAS) * DAS2R;
  let dp = 0;
  // Somma dai termini più piccoli, come eraNut00b.
  for (let i = N - 1; i >= 0; i--) {
    const o = 8 * i;
    const arg =
      (TERMINI[o]! * el + TERMINI[o + 1]! * elp + TERMINI[o + 2]! * f + TERMINI[o + 3]! * d + TERMINI[o + 4]! * om) % D2PI;
    dp += (TERMINI[o + 5]! + TERMINI[o + 6]! * t) * Math.sin(arg) + TERMINI[o + 7]! * Math.cos(arg);
  }
  return dp * U2R + DPPLAN;
}
